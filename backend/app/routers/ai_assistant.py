def _is_public_kb_whitelisted(filename: str) -> bool:
    """Checks whether a Knowledge Base file is on the strict Public AI Whitelist."""
    if not filename:
        return False
    stem = Path(str(filename).strip()).stem.strip().lower()
    stem_norm = re.sub(r"[\s_]+", "_", stem)
    stem_base = re.sub(r"_არგონ$", "", stem_norm)
    return stem_base in PUBLIC_KB_WHITELIST_BASE_STEMS


