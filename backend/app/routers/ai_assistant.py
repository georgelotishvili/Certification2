def _strip_internal_annexes_for_public(filename: str, text: str) -> str:
    fname_norm = re.sub(r"[\s_]+", "_", str(filename or "").lower())
    if "03_მიუკერძოებლობის_პოლიტიკა" in fname_norm:
        # For Public AI: keep only Articles 1 through 9; strip Section 10 (internal doc codes)
        # and Annex 1 ("დანართი 1 / დანართი №1 — მიუკერძოებლობის რისკების რეესტრი").
        cut_match = re.search(
            r"(?:^|\n)\s*(?:---\s*\n+\s*)?(?:#{1,4}\s*(?:10\.\s*დაკავშირებული\s*დოკუმენტები|დანართი\s*№?\s*1\b)|დანართი\s*№?\s*1\s*[—:\-])",
            text,
        )
        if cut_match and cut_match.start() > 0:
            text = text[: cut_match.start()].rstrip()
    # Replace legal address mentions with actual office/exam center address for public chat
    text = re.sub(
        r"იოსებიძის\s*ქ(?:უჩა|\.)?\s*№?\s*69(?:,\s*ბინა\s*№?\s*28)?",
        "მირიან მეფის ქუჩა №98, მე-2 სართული, საოფისე ფართი №6",
        text,
    )
    return text


def _select_relevant_sections_from_large_text(text: str, query_stems: list[str], max_chars: int = 16000) -> str:
    if len(text) <= max_chars:
        return text
    if not query_stems:
        return text[:max_chars] + "\n...[დოკუმენტის გაგრძელება შემოკლებულია]..."

    # Split into chunks of ~3500 chars along paragraph boundaries
    paragraphs = re.split(r"\n\s*\n", text)
    chunks: list[str] = []
    cur: list[str] = []
    cur_len = 0
    for p in paragraphs:
        p_str = p.strip()
        if not p_str:
            continue
        if cur_len + len(p_str) > 3500 and cur:
            chunks.append("\n\n".join(cur))
            cur = [p_str]
            cur_len = len(p_str)
        else:
            cur.append(p_str)
            cur_len += len(p_str) + 2
    if cur:
        chunks.append("\n\n".join(cur))

    # Calculate IDF-like rarity weight per stem across chunks so specific terms rank highest
    chunks_lower = [c.lower() for c in chunks]
    stem_weights: dict[str, int] = {}
    total_c = max(1, len(chunks_lower))
    for st in query_stems:
        df = sum(1 for cl in chunks_lower if st in cl)
        if df > 0:
            stem_weights[st] = max(6, int((total_c * 18) / df))

    scored_chunks: list[tuple[int, int, str]] = []
    for idx, (ch, ch_lower) in enumerate(zip(chunks, chunks_lower)):
        sc = 0
        for st, w in stem_weights.items():
            if st in ch_lower:
                sc += w + min(ch_lower.count(st), 5) * 3
        if idx == 0:
            sc += 3  # Slight boost to document header/intro
        scored_chunks.append((sc, -idx, ch))

    scored_chunks.sort(reverse=True)
    selected: list[tuple[int, str]] = []
    used_chars = 0
    for sc, neg_idx, ch in scored_chunks:
        if sc <= 0 and selected:
            break
        if used_chars + len(ch) > max_chars:
            continue
        selected.append((-neg_idx, ch))
        used_chars += len(ch) + 10
        if len(selected) >= 6:
            break

    selected.sort(key=lambda x: x[0])
    return "\n\n---\n\n".join(ch for _, ch in selected)


